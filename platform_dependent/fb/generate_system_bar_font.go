//go:build ignore

// Generate the fixed-size status alphabet with the terminal's existing
// FreeType renderer. Only this build tool uses cgo, not the framebuffer host.
package main

/*
#cgo CFLAGS: -I${SRCDIR}/../../third_party/freetype/include -I${SRCDIR}/../..
#cgo LDFLAGS: ${SRCDIR}/../../third_party/freetype/libfreetype.a -lm -lpthread
#include <stdlib.h>
#include "third_party_wrapper/ff2.h"
#include "third_party_wrapper/plugin-ff2.c"

static int load_status_font(const char *path, int size) {
	char *paths[] = {(char *)path};
	return ft_init(paths, 1, size);
}
*/
import "C"

import (
	"bytes"
	"compress/zlib"
	"crypto/sha256"
	"encoding/base64"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"unsafe"
)

const (
	fontSize = 28
	alphabet = " %-0123456789:ABT"
)

func main() {
	font := flag.String("font", "Monaco_Linux.ttf", "bundled Monaco font")
	output := flag.String("output", "system_bar_font_generated.go", "generated Go source")
	flag.Parse()
	if err := generate(*font, *output); err != nil {
		log.Fatal(err)
	}
}

func generate(font, output string) error {
	fontData, err := os.ReadFile(font)
	if err != nil {
		return err
	}
	path := C.CString(font)
	defer C.free(unsafe.Pointer(path))
	if C.load_status_font(path, fontSize) == 0 {
		return fmt.Errorf("cannot load Monaco at %d pixels", fontSize)
	}
	defer C.ft_cleanup()
	var ascent, descent, advance C.int
	if C.ft_metrics(&ascent, &descent, &advance) == 0 {
		return fmt.Errorf("cannot read Monaco metrics")
	}
	w, h := int(advance), int(ascent+descent)
	if w < 1 || h < 1 || w > 128 || h > 128 {
		return fmt.Errorf("invalid Monaco cell %dx%d", w, h)
	}
	coverage := make([]byte, len(alphabet)*w*h)
	for i, ch := range alphabet {
		if ch == ' ' {
			continue
		}
		glyph := make([]uint32, w*h)
		text := C.CString(string(ch))
		ok := C.make_ff2_glyph(text, 0xffffffff, 0xff000000, advance, ascent+descent, ascent, (*C.uint32_t)(unsafe.Pointer(&glyph[0])))
		C.free(unsafe.Pointer(text))
		if ok == 0 {
			return fmt.Errorf("cannot rasterize Monaco character %q", ch)
		}
		for at, pixel := range glyph {
			coverage[i*w*h+at] = byte(pixel)
		}
	}
	var packed bytes.Buffer
	zw := zlib.NewWriter(&packed)
	if _, err := zw.Write(coverage); err != nil {
		return err
	}
	if err := zw.Close(); err != nil {
		return err
	}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by generate_system_bar_font.go; DO NOT EDIT.\n//go:build linux\n\npackage fb")
	fmt.Fprintf(&source, "\nconst (\n systemBarFontSize = %d\n systemBarFontCellWidth = %d\n systemBarFontCellHeight = %d\n systemBarFontAlphabet = %q\n systemBarFontSourceSHA256 = %q\n)\n", fontSize, w, h, alphabet, fmt.Sprintf("%x", sha256.Sum256(fontData)))
	fmt.Fprintln(&source, "\n// Zlib-compressed grayscale coverage, one row-major cell per alphabet byte.\nconst systemBarFontAlphaBase64 =")
	encoded := base64.StdEncoding.EncodeToString(packed.Bytes())
	for len(encoded) > 96 {
		fmt.Fprintf(&source, "%q +\n", encoded[:96])
		encoded = encoded[96:]
	}
	fmt.Fprintf(&source, "%q\n", encoded)
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	// Publish only complete formatted output, even when a build is interrupted.
	f, err := os.CreateTemp(filepath.Dir(output), ".status-font-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(formatted); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), output)
}
