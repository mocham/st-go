//go:build ignore

// Generate the fixed-size status alphabet with the terminal's Go rasterizer.
package main

import (
	"bytes"
	"compress/zlib"
	"crypto/sha256"
	"encoding/base64"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"st-go/platform_neutral/fontraster"
)

const (
	fontSize = 28
	// Preserve the bar/icon layout independently of font-engine advances.
	cellWidth  = 21
	cellHeight = 35
	baseline   = 28
	alphabet   = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~"
)

func main() {
	font := flag.String("font", "Monaco_Linux.ttf", "bundled Monaco font")
	output := flag.String("output", "functionalities/widgets/systembar/font_generated.go", "generated Go source")
	flag.Parse()
	if err := generate(*font, *output); err != nil {
		log.Fatal(err)
	}
}

func generate(font, output string) error {
	fontData, err := os.ReadFile(font)
	if err != nil {
		return err
	}
	face, err := fontraster.OpenGo(fontData, fontSize)
	if err != nil {
		return err
	}
	defer face.Close()
	w, h := cellWidth, cellHeight
	coverage := make([]byte, len(alphabet)*w*h)
	for i, ch := range alphabet {
		if ch == ' ' {
			continue
		}
		mask, found, err := face.Glyph(ch)
		if err != nil || !found {
			return fmt.Errorf("cannot rasterize Monaco character %q: %v", ch, err)
		}
		glyph := fontraster.Compose(mask, 0xffffffff, 0xff000000, w, h, baseline)
		for at, pixel := range glyph {
			coverage[i*w*h+at] = byte(pixel)
		}
	}
	var packed bytes.Buffer
	zw := zlib.NewWriter(&packed)
	if _, err := zw.Write(coverage); err != nil {
		return err
	}
	if err := zw.Close(); err != nil {
		return err
	}
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by generate_system_bar_font.go; DO NOT EDIT.\n\npackage systembar")
	fmt.Fprintf(&source, "\nconst (\n systemBarFontSize = %d\n systemBarFontCellWidth = %d\n systemBarFontCellHeight = %d\n systemBarFontAlphabet = %q\n systemBarFontSourceSHA256 = %q\n)\n", fontSize, w, h, alphabet, fmt.Sprintf("%x", sha256.Sum256(fontData)))
	fmt.Fprintln(&source, "\n// Zlib-compressed grayscale coverage, one row-major cell per alphabet byte.\nconst systemBarFontAlphaBase64 =")
	encoded := base64.StdEncoding.EncodeToString(packed.Bytes())
	for len(encoded) > 96 {
		fmt.Fprintf(&source, "%q +\n", encoded[:96])
		encoded = encoded[96:]
	}
	fmt.Fprintf(&source, "%q\n", encoded)
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	// Publish only complete formatted output, even when a build is interrupted.
	f, err := os.CreateTemp(filepath.Dir(output), ".status-font-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(formatted); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0644); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), output)
}
